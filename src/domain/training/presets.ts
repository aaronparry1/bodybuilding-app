export const defaultHypertrophySettings = {
  repRange: { min: 8, max: 12 },
  dropOffPercent: 15,
  loadIncrease: 2.5,
  unit: "kg" as const,
  requiredWorkSets: 3,
};

type ExerciseSeed = {
  id: string;
  name: string;
  category: MuscleGroup;
  primaryMuscles: MuscleGroup[];
  secondaryMuscles?: MuscleGroup[];
  equipment: Equipment[];
  movementPattern: MovementPattern;
  kind: ExerciseKind;
  role?: ExerciseRole;
  roles?: ExerciseRole[];
  family?: ExerciseFamily;
  tier?: ExerciseTier;
  fatigueCost?: ExerciseFatigueCost;
  jointStress?: JointStressEstimate;
  suitability?: ExerciseSuitability[];
  repRange?: { min: number; max: number };
  measurementType?: ExerciseMeasurementType;
  durationIncreaseSeconds?: number;
  loadJump?: number;
  beginner?: boolean;
  advanced?: boolean;
  suitableBlocks?: BlockCompatibility[];
  swapTags?: string[];
  notes: string[];
};

function createExercise(seed: ExerciseSeed): Exercise {
  const defaultRepRange = seed.repRange ?? defaultHypertrophySettings.repRange;
  const measurementType = seed.measurementType ?? "reps";
  const defaultLoadJump = seed.loadJump ?? (measurementType === "duration" ? 0 : seed.kind === "barbell" || seed.kind === "machine" ? 5 : 2.5);
  const role = seed.role ?? seed.roles?.[0] ?? inferPrimaryExerciseRole(seed);
  const roles = seed.roles ?? inferExerciseRoles(seed);
  const family = seed.family ?? inferExerciseFamily(seed, role);
  const tier = seed.tier ?? inferExerciseTier(seed, role);
  const suitability = seed.suitability ?? inferExerciseSuitability(seed);
  const fatigueCost = seed.fatigueCost ?? inferFatigueCost(seed, role);
  const jointStress = seed.jointStress ?? inferJointStress(seed, role);

  return {
    id: seed.id,
    name: seed.name,
    category: seed.category,
    primaryMuscles: seed.primaryMuscles,
    secondaryMuscles: seed.secondaryMuscles ?? [],
    equipment: seed.equipment,
    movementPattern: seed.movementPattern,
    defaultRepRange,
    measurementType,
    defaultLoadJump,
    unitCompatibility: ["kg", "lb"],
    kind: seed.kind,
    role,
    roles,
    family,
    tier,
    fatigueCost,
    jointStress,
    suitability,
    isBeginnerFriendly: seed.beginner ?? suitability.includes("beginner"),
    isAdvanced: seed.advanced ?? !suitability.includes("beginner"),
    notes: seed.notes,
    suitableBlocks: seed.suitableBlocks ?? ["hypertrophy", "powerbuilding", "strength_hypertrophy", "strength", "power", "peak", "deload"],
    macrocycleEngines: [...inferMacrocycleEngines(seed)],
    mesocycleEligibility: inferMesocycleEligibility(seed),
    sessionRoleEligibility: inferSessionRoleEligibility(seed),
    setMethodEligibility: inferSetMethodEligibility(seed),
    competitionLift: isCompetitionLift(seed),
    swapTags: seed.swapTags ?? [seed.category, seed.movementPattern, seed.kind, role, family, tier, ...seed.equipment],
    createdByUserId: null,
    isCustom: false,
    defaultSettings: {
      ...defaultHypertrophySettings,
      repRange: defaultRepRange,
      ...(measurementType === "duration" ? { measurementType, durationIncreaseSeconds: seed.durationIncreaseSeconds ?? 5 } : {}),
      loadIncrease: defaultLoadJump,
    },
  };
}

function inferMacrocycleEngines(seed: ExerciseSeed) { return seed.movementPattern === "carry" || seed.movementPattern === "core" ? ["hypertrophy", "powerbuilding", "strength", "athletic_performance"] as const : seed.kind === "barbell" ? ["hypertrophy", "powerbuilding", "strength", "athletic_performance"] as const : ["hypertrophy", "powerbuilding", "strength", "athletic_performance"] as const; }
function inferMesocycleEligibility(seed: ExerciseSeed) { return seed.suitableBlocks ?? ["hypertrophy", "powerbuilding", "strength_hypertrophy", "strength", "power", "peak", "deload"]; }
function inferSessionRoleEligibility(seed: ExerciseSeed) { return [seed.movementPattern, seed.category]; }
function inferSetMethodEligibility(seed: ExerciseSeed) { return seed.kind === "barbell" && (seed.movementPattern === "squat" || seed.movementPattern === "hinge" || seed.movementPattern.includes("push")) ? ["exact_straight_sets", "top_set_backoffs", "five_three_one", "eight_across"] : ["exact_straight_sets", "controlled_performance_set"]; }
function isCompetitionLift(seed: ExerciseSeed) { return /barbell (back squat|bench press|deadlift)/i.test(seed.id); }

function inferPrimaryExerciseRole(seed: ExerciseSeed): ExerciseRole {
  if (seed.role) return seed.role;
  if (seed.roles?.length) return seed.roles[0]!;
  if (seed.movementPattern === "core" || seed.movementPattern === "carry") return "accessory";
  if (seed.movementPattern === "isolation") return "isolation";
  if (seed.movementPattern === "hinge" && seed.kind === "bodyweight") return "accessory";
  if (seed.kind === "barbell" || seed.movementPattern === "squat" || seed.movementPattern === "hinge") return "primary_compound";
  return "secondary_compound";
}

function inferExerciseRoles(seed: ExerciseSeed): ExerciseRole[] {
  const primaryRole = inferPrimaryExerciseRole(seed);
  if (seed.movementPattern === "core" || seed.movementPattern === "carry") return [primaryRole, "corrective"];
  return [primaryRole];
}

function inferExerciseFamily(seed: ExerciseSeed, role: ExerciseRole): ExerciseFamily {
  const name = seed.name.toLowerCase();
  if (name.includes("back extension") || name.includes("reverse hyper")) return "hyperextension";
  if (role === "power" && name.includes("clean")) return "olympic_power";
  if (role === "power" && (name.includes("jump") || name.includes("swing"))) return "jump_power";
  if (role === "power" && name.includes("throw")) return "throw_power";
  if (name.includes("face pull") || name.includes("rear delt") || name.includes("reverse fly")) return "rear_delt_corrective";
  if (seed.category === "chest" && seed.movementPattern === "isolation") return "chest_isolation";
  if ((seed.category === "shoulders" || seed.category === "rear_delts") && seed.movementPattern === "isolation") return "shoulder_isolation";
  if (seed.category === "triceps" && seed.movementPattern === "isolation") return "triceps_isolation";
  if (seed.category === "biceps" && seed.movementPattern === "isolation") return "biceps_isolation";
  if (seed.category === "calves") return "calf_raise";
  if (seed.category === "forearms") return "forearm";
  if (seed.category === "traps") return seed.movementPattern === "carry" ? "carry" : "trap";
  if (seed.category === "adductors") return "adductor";
  if (seed.category === "abductors") return "abductor";
  if (seed.category === "quads" && seed.movementPattern === "isolation") return "quad_isolation";
  if (seed.category === "hamstrings" && seed.movementPattern === "isolation") return "hamstring_isolation";
  if (seed.category === "glutes" && seed.movementPattern === "isolation") return "glute_isolation";
  if (seed.movementPattern === "horizontal_push") return "horizontal_press";
  if (seed.movementPattern === "vertical_push") return "vertical_press";
  if (seed.movementPattern === "vertical_pull") return "vertical_pull";
  if (seed.movementPattern === "horizontal_pull") return "horizontal_pull";
  if (seed.movementPattern === "squat") return "squat_pattern";
  if (seed.movementPattern === "hinge") return "hip_hinge";
  if (seed.movementPattern === "hip_thrust") return "hip_thrust";
  if (seed.movementPattern === "lunge") return "single_leg";
  if (seed.movementPattern === "core") return name.includes("plank") || name.includes("bird dog") ? "core_stability" : "core_flexion";
  if (seed.movementPattern === "carry") return "carry";
  return "other";
}

function inferExerciseTier(seed: ExerciseSeed, role: ExerciseRole): ExerciseTier {
  if (role === "power") return seed.name.toLowerCase().includes("clean") ? "A" : "B";
  if (role === "primary_compound") return "A";
  if (role === "secondary_compound" || role === "accessory") return "B";
  return "C";
}

function inferExerciseSuitability(seed: ExerciseSeed): ExerciseSuitability[] {
  if (seed.advanced) return ["intermediate", "advanced"];
  if (seed.beginner) return ["beginner", "intermediate", "advanced"];
  if (seed.kind === "barbell" && (seed.movementPattern === "squat" || seed.movementPattern === "hinge")) return ["intermediate", "advanced"];
  return ["beginner", "intermediate", "advanced"];
}

function inferFatigueCost(seed: ExerciseSeed, role: ExerciseRole): ExerciseFatigueCost {
  if (role === "power" || role === "primary_compound") return "high";
  if (role === "secondary_compound" || role === "accessory") return "moderate";
  return "low";
}

function inferJointStress(seed: ExerciseSeed, role: ExerciseRole): JointStressEstimate {
  if (role === "primary_compound" && (seed.kind === "barbell" || seed.kind === "smith")) return "high";
  if (seed.movementPattern === "isolation" || seed.movementPattern === "core") return "low";
  return "moderate";
}

