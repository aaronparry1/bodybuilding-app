export const exerciseLibrary: Exercise[] = [...baseExerciseLibrary, ...expandedExerciseSeeds.map(createExercise)];

const exerciseById = new Map(exerciseLibrary.map((exercise) => [exercise.id, exercise]));

function settingsFor(exerciseId: string, overrides: Partial<ProgressionSettings> = {}): ProgressionSettings {
  const exercise = exerciseById.get(exerciseId);
  return withSetPrescription({
    ...(exercise?.defaultSettings ?? defaultHypertrophySettings),
    ...overrides,
    repRange: overrides.repRange ?? exercise?.defaultSettings.repRange ?? defaultHypertrophySettings.repRange,
  }, {
    exerciseRole: exercise?.role,
    exerciseFamily: exercise?.family,
    primaryMuscles: exercise?.primaryMuscles,
  }, {
    source: "generated",
  });
}

function slot(id: string, exerciseId: string, plannedOrder: number, overrides?: Partial<ProgressionSettings>) {
  return {
    id,
    exerciseId,
    plannedOrder,
    settings: settingsFor(exerciseId, overrides),
  };
}

